/**
  * @brief  Ben Katz 30-Cycle Fast Table-Based Sine and Cosine with Linear Interpolation
  */
void sincos_lut(float theta, float *s, float *c) {
    float k = theta * INV_TWO_PI_F;         // Angle in revolutions
    k = k - (float)(int)k;                  // Fractional revolution (-1, 1)
    if (k < 0.0f) { k += 1.0f; }            // Wrap to [0, 1)
    if (k >= 1.0f) { k = 0.0f; }

    float idx = k * 512.0f;
    int i = (int)idx;                       // 0..511
    float frac = idx - (float)i;

    float s0 = sin_tab[i];                  // sin_tab has 513 entries (i+1 always valid)
    *s = s0 + frac * (sin_tab[i + 1] - s0);
    int j = (i + 128) & 511;                // cos(theta) = sin(theta + pi/2) = 128 steps ahead
    float c0 = sin_tab[j];
    *c = c0 + frac * (sin_tab[j + 1] - c0);
}

float sin_lut(float theta) {
    float s, c;
    sincos_lut(theta, &s, &c);
    return s;
}

float cos_lut(float theta) {
    float s, c;
    sincos_lut(theta, &s, &c);
    return c;
}

void limit_norm(float *x, float *y, float limit) {
    float norm = sqrtf((*x) * (*x) + (*y) * (*y));
    if (norm > limit && norm > 0.0001f) {
        float scale = limit / norm;
        *x *= scale;
        *y *= scale;
    }
}

int float_to_uint(float x, float x_min, float x_max, int bits) {
    float span = x_max - x_min;
    float offset = x_min;
    if (span <= 0.0f) return 0;
    return (int)((x - offset) * ((float)((1 << bits) - 1)) / span);
}

float uint_to_float(int x_int, float x_min, float x_max, int bits) {
    float span = x_max - x_min;
    float offset = x_min;
    return ((float)x_int) * span / ((float)((1 << bits) - 1)) + offset;
}

void utils_fast_sincos(float angle, float *sin, float *cos) {
    sincos_lut(angle, sin, cos);
}

void utils_fast_sincos_better(float angle, float *sin, float *cos) {
    sincos_lut(angle, sin, cos);
}

float utils_min_abs(float va, float vb) {
	float res;
	if (fabsf(va) < fabsf(vb)) {
		res = va;
	} else {
		res = vb;
	}
	return res;
}

float utils_max_abs(float va, float vb) {
	float res;
	if (fabsf(va) > fabsf(vb)) {
		res = va;
	} else {
		res = vb;
	}
	return res;
}

float utils_middle_of_3(float a, float b, float c) {
	float middle;

	if ((a <= b) && (a <= c)) {
		middle = (b <= c) ? b : c;
	} else if ((b <= a) && (b <= c)) {
		middle = (a <= c) ? a : c;
	} else {
		middle = (a <= b) ? a : b;
	}
	return middle;
}

int utils_middle_of_3_int(int a, int b, int c) {
	int middle;

	if ((a <= b) && (a <= c)) {
		middle = (b <= c) ? b : c;
	} else if ((b <= a) && (b <= c)) {
		middle = (a <= c) ? a : c;
	} else {
		middle = (a <= b) ? a : b;
	}
	return middle;
}

float utils_interpolate_angles_rad(float a1, float a2, float weight_a1) {
	while ((a1 - a2) > M_PI) a2 += 2.0 * M_PI;
	while ((a2 - a1) > M_PI) a1 += 2.0 * M_PI;

	float res = a1 * weight_a1 + a2 * (1.0 - weight_a1);
	utils_norm_angle_rad(&res);
	return res;
}

