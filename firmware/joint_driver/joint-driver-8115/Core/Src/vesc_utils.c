float utils_fast_atan2(float y, float x) {
	float abs_y = fabsf(y) + 1e-20; // kludge to prevent 0/0 condition
	float angle;

	if (x >= 0) {
		float r = (x - abs_y) / (x + abs_y);
		float rsq = r * r;
		angle = ((0.1963 * rsq) - 0.9817) * r + (M_PI / 4.0);
	} else {
		float r = (x + abs_y) / (abs_y - x);
		float rsq = r * r;
		angle = ((0.1963 * rsq) - 0.9817) * r + (3.0 * M_PI / 4.0);
	}

	UTILS_NAN_ZERO(angle);

	if (y < 0) {
		return(-angle);
	} else {
		return(angle);
	}
}

float utils_fast_sin(float angle) {
	while (angle < -M_PI) {
		angle += 2.0 * M_PI;
	}

	while (angle >  M_PI) {
		angle -= 2.0 * M_PI;
	}

	float res = 0.0;

	if (angle < 0.0) {
		res = 1.27323954 * angle + 0.405284735 * angle * angle;
	} else {
		res = 1.27323954 * angle - 0.405284735 * angle * angle;
	}

	return res;
}

float utils_fast_cos(float angle) {
	angle += 0.5 * M_PI;

	while (angle < -M_PI) {
		angle += 2.0 * M_PI;
	}

	while (angle >  M_PI) {
		angle -= 2.0 * M_PI;
	}

	float res = 0.0;

	if (angle < 0.0) {
		res = 1.27323954 * angle + 0.405284735 * angle * angle;
	} else {
		res = 1.27323954 * angle - 0.405284735 * angle * angle;
	}

	return res;
}

